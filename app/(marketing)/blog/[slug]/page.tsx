// Markdown-like content renderer (simplified)
function renderContent(content: string) {
  const lines = content.split('\n');
  const elements: React.ReactNode[] = [];
  let currentList: string[] = [];
  let listType: 'ul' | 'ol' | null = null;

  const flushList = () => {
    if (currentList.length > 0) {
      if (listType === 'ol') {
        elements.push(
          <ol key={`ol-${elements.length}`} className="list-decimal list-inside space-y-2 my-4 ml-4">
            {currentList.map((item, i) => (
              <li key={i} className="text-gray-600 dark:text-gray-300">{item}</li>
            ))}
          </ol>
        );
      } else {
        elements.push(
          <ul key={`ul-${elements.length}`} className="list-disc list-inside space-y-2 my-4 ml-4">
            {currentList.map((item, i) => (
              <li key={i} className="text-gray-600 dark:text-gray-300">{item}</li>
            ))}
          </ul>
        );
      }
      currentList = [];
      listType = null;
    }
  };

  lines.forEach((line, index) => {
    const trimmedLine = line.trim();
    
    if (!trimmedLine) {
      flushList();
      return;
    }

    // Headers
    if (trimmedLine.startsWith('# ')) {
      flushList();
      elements.push(
        <h1 key={index} className="text-3xl md:text-4xl font-bold text-gray-900 dark:text-white mt-8 mb-4">
          {trimmedLine.slice(2)}
        </h1>
      );
      return;
    }

    if (trimmedLine.startsWith('## ')) {
      flushList();
      elements.push(
        <h2 key={index} className="text-2xl md:text-3xl font-bold text-gray-900 dark:text-white mt-8 mb-4">
          {trimmedLine.slice(3)}
        </h2>
      );
      return;
    }

    if (trimmedLine.startsWith('### ')) {
      flushList();
      elements.push(
        <h3 key={index} className="text-xl md:text-2xl font-semibold text-gray-900 dark:text-white mt-6 mb-3">
          {trimmedLine.slice(4)}
        </h3>
      );
      return;
    }

    // Ordered list
    if (/^\d+\.\s/.test(trimmedLine)) {
      if (listType !== 'ol') {
        flushList();
        listType = 'ol';
      }
      currentList.push(trimmedLine.replace(/^\d+\.\s/, '').replace(/\*\*(.*?)\*\*/g, '$1'));
      return;
    }

    // Unordered list
    if (trimmedLine.startsWith('- ')) {
      if (listType !== 'ul') {
        flushList();
        listType = 'ul';
      }
      currentList.push(trimmedLine.slice(2).replace(/\*\*(.*?)\*\*/g, '$1'));
      return;
    }

    // Regular paragraph
    flushList();
    
    // Process inline formatting
    let processedLine = trimmedLine
      .replace(/\*\*(.*?)\*\*/g, '<strong class="font-semibold text-gray-900 dark:text-white">$1</strong>')
      .replace(/\*(.*?)\*/g, '<em>$1</em>')
      .replace(/\[(.*?)\]\((.*?)\)/g, '<a href="$2" class="text-purple-600 hover:text-purple-700 underline">$1</a>');

    elements.push(
      <p 
        key={index} 
        className="text-gray-600 dark:text-gray-300 leading-relaxed my-4"
        dangerouslySetInnerHTML={{ __html: processedLine }}
      />
    );
  });

  flushList();
  return elements;
}

// Share button component
function ShareButton({ 
  platform, 
  url, 
  title 
}: { 
  platform: 'twitter' | 'facebook' | 'linkedin' | 'copy';
  url: string;
  title: string;
}) {
  const shareUrls = {
    twitter: `https://twitter.com/intent/tweet?text=${encodeURIComponent(title)}&url=${encodeURIComponent(url)}`,
    facebook: `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`,
    linkedin: `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`,
    copy: url
  };

  const icons = {
    twitter: <Twitter className="h-4 w-4" />,
    facebook: <Facebook className="h-4 w-4" />,
    linkedin: <Linkedin className="h-4 w-4" />,
    copy: <Link2 className="h-4 w-4" />
  };

  const labels = {
    twitter: 'Twitter',
    facebook: 'Facebook',
    linkedin: 'LinkedIn',
    copy: 'Copy Link'
  };

  if (platform === 'copy') {
    return (
      <Button
        variant="outline"
        size="sm"
        className="gap-2"
        onClick={() => {
          navigator.clipboard.writeText(url);
          // In a real app, show a toast notification
        }}
      >
        {icons[platform]}
        <span className="hidden sm:inline">{labels[platform]}</span>
      </Button>
    );
  }

  return (
    <Button
      variant="outline"
      size="sm"
      className="gap-2"
      asChild
    >
      <a href={shareUrls[platform]} target="_blank" rel="noopener noreferrer">
        {icons[platform]}
        <span className="hidden sm:inline">{labels[platform]}</span>
      </a>
    </Button>
  );
}

// Table of Contents component
function TableOfContents({ content }: { content: string }) {
  const headings = content
    .split('\n')
    .filter(line => line.trim().startsWith('## ') || line.trim().startsWith('### '))
    .map(line => {
      const level = line.startsWith('### ') ? 3 : 2;
      const text = line.replace(/^#+\s/, '').trim();
      const id = text.toLowerCase().replace(/\s+/g, '-').replace(/[^\w-]/g, '');
      return { level, text, id };
    });

  if (headings.length < 3) return null;

  return (
    <Card className="sticky top-24 hidden xl:block">
      <CardContent className="p-4">
        <h4 className="font-semibold text-sm text-gray-900 dark:text-white mb-3">
          Table of Contents
        </h4>
        <nav className="space-y-2">
          {headings.map((heading, index) => (
            <a
              key={index}
              href={`#${heading.id}`}
              className={`block text-sm text-gray-600 dark:text-gray-400 hover:text-purple-600 dark:hover:text-purple-400 transition-colors ${
                heading.level === 3 ? 'ml-4' : ''
              }`}
            >
              {heading.text}
            </a>
          ))}
        </nav>
      </CardContent>
    </Card>
  );
}

