// Get blog post by slug
function getBlogPost(slug: string): BlogPost | undefined {
  return blogPosts.find(post => post.slug === slug);
}

// Get related posts
function getRelatedPosts(currentSlug: string, category: string, limit: number = 3): BlogPost[] {
  return blogPosts
    .filter(post => post.slug !== currentSlug)
    .filter(post => post.category === category || post.tags.some(tag => 
      blogPosts.find(p => p.slug === currentSlug)?.tags.includes(tag)
    ))
    .slice(0, limit);
}

// Get adjacent posts for navigation
function getAdjacentPosts(currentSlug: string): { prev: BlogPost | null; next: BlogPost | null } {
  const currentIndex = blogPosts.findIndex(post => post.slug === currentSlug);
  return {
    prev: currentIndex > 0 ? blogPosts[currentIndex - 1] : null,
    next: currentIndex < blogPosts.length - 1 ? blogPosts[currentIndex + 1] : null
  };
}

