import { UserDataExport } from './dataCollector';

/**
 * Generate a readable HTML report from user data export.
 */
export function generateHtmlReport(data: UserDataExport): string {
  const profile = (data.profile as Record<string, unknown>) || {};

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Your Removation.ai Data Export</title>
  <style>
    body { font-family: Arial, sans-serif; max-width: 900px; margin: 40px auto; padding: 0 20px; color: #333; }
    h1 { color: #6B21A8; border-bottom: 3px solid #6B21A8; padding-bottom: 10px; }
    h2 { color: #374151; margin-top: 32px; border-left: 4px solid #6B21A8; padding-left: 12px; }
    .meta { background: #F3F4F6; padding: 16px; border-radius: 8px; margin-bottom: 24px; }
    .meta p { margin: 4px 0; font-size: 14px; }
    table { width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 14px; }
    th { background: #6B21A8; color: white; padding: 8px 12px; text-align: left; }
    td { border: 1px solid #E5E7EB; padding: 8px 12px; vertical-align: top; }
    tr:nth-child(even) td { background: #F9FAFB; }
    .empty { color: #9CA3AF; font-style: italic; }
    .footer { margin-top: 48px; padding-top: 16px; border-top: 1px solid #E5E7EB; font-size: 12px; color: #6B7280; }
    pre { font-size: 11px; margin: 0; white-space: pre-wrap; word-break: break-all; }
  </style>
</head>
<body>
  <h1>Your Removation.ai Data Export</h1>
  <div class="meta">
    <p><strong>Exported at:</strong> ${new Date(data.exportedAt).toLocaleString()}</p>
    <p><strong>Account:</strong> ${profile.email || 'N/A'}</p>
    <p><strong>Total projects:</strong> ${data._meta.totalProjects}</p>
    <p><strong>Total renders:</strong> ${data._meta.totalRenders}</p>
    <p><strong>Total bookings:</strong> ${data._meta.totalBookings}</p>
  </div>

  <h2>Profile Information</h2>
  <table>
    ${Object.entries(profile)
      .filter(([k]) => !['_id', '__v', 'password', 'otp'].includes(k))
      .map(([k, v]) => `<tr><th>${k}</th><td>${formatValue(v)}</td></tr>`)
      .join('')}
  </table>

  <h2>Projects (${data.projects.length})</h2>
  ${data.projects.length === 0
    ? '<p class="empty">No projects found.</p>'
    : renderTable(data.projects as Record<string, unknown>[], ['_id', 'name', 'createdAt', 'updatedAt'])}

  <h2>Renders (${data.renders.length})</h2>
  ${data.renders.length === 0
    ? '<p class="empty">No renders found.</p>'
    : renderTable(data.renders as Record<string, unknown>[], ['_id', 'mode', 'status', 'createdAt'])}

  <h2>Bookings (${data.bookings.length})</h2>
  ${data.bookings.length === 0
    ? '<p class="empty">No bookings found.</p>'
    : renderTable(data.bookings as Record<string, unknown>[], ['_id', 'status', 'createdAt'])}

  <h2>Reviews (${data.reviews.length})</h2>
  ${data.reviews.length === 0
    ? '<p class="empty">No reviews found.</p>'
    : renderTable(data.reviews as Record<string, unknown>[], ['_id', 'rating', 'comment', 'createdAt'])}

  <h2>Subscription</h2>
  ${!data.subscription
    ? '<p class="empty">No subscription record found.</p>'
    : renderTable([data.subscription as Record<string, unknown>], ['plan', 'status', 'currentPeriodStart', 'currentPeriodEnd'])}

  <div class="footer">
    <p>This export was generated by Removation.ai in response to your data export request.</p>
    <p>This file contains all personal data we hold about you as of the export date.</p>
    <p>For questions contact: privacy@removation.ai</p>
  </div>
</body>
</html>`;
}

function formatValue(v: unknown): string {
  if (v === null || v === undefined) return '<span class="empty">—</span>';
  if (v instanceof Date) return new Date(v).toLocaleString();
  if (typeof v === 'object') return `<pre>${JSON.stringify(v, null, 2)}</pre>`;
  if (typeof v === 'string' && v.startsWith('http')) return `<a href="${v}" target="_blank">${v}</a>`;
  return String(v);
}

function renderTable(rows: Record<string, unknown>[], preferredCols?: string[]): string {
  if (!rows.length) return '<p class="empty">None found.</p>';
  const cols = preferredCols?.filter(c => rows[0][c] !== undefined) || Object.keys(rows[0]).slice(0, 6);
  return `<table>
    <thead><tr>${cols.map(c => `<th>${c}</th>`).join('')}</tr></thead>
    <tbody>${rows.map(r => `<tr>${cols.map(c => `<td>${formatValue(r[c])}</td>`).join('')}</tr>`).join('')}</tbody>
  </table>`;
}
