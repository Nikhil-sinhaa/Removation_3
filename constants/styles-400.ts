// Helper functions
export const getStylesByCategory = (category: StyleCategory): DesignStyle[] => {
  return DESIGN_STYLES.filter(style => style.category === category);
};

export const getPopularStyles = (limit: number = 20): DesignStyle[] => {
  return [...DESIGN_STYLES]
    .sort((a, b) => b.popularity - a.popularity)
    .slice(0, limit);
};

export const getPremiumStyles = (): DesignStyle[] => {
  return DESIGN_STYLES.filter(style => style.premium);
};

export const getFreeStyles = (): DesignStyle[] => {
  return DESIGN_STYLES.filter(style => !style.premium);
};

export const searchStyles = (query: string): DesignStyle[] => {
  const lowerQuery = query.toLowerCase();
  return DESIGN_STYLES.filter(
    style =>
      style.name.toLowerCase().includes(lowerQuery) ||
      style.nameHi.includes(query) ||
      style.keywords.some(k => k.includes(lowerQuery)) ||
      style.description.toLowerCase().includes(lowerQuery)
  );
};

export const getStyleById = (id: string): DesignStyle | undefined => {
  return DESIGN_STYLES.find(style => style.id === id);
};

export const getIndianStyles = (): DesignStyle[] => {
  return DESIGN_STYLES.filter(style => style.category === 'regional');
};