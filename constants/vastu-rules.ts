// Helper functions
export const getRulesByCategory = (category: VastuCategory): VastuRule[] => {
  return VASTU_RULES.filter((rule) => rule.category === category);
};

export const getRulesBySeverity = (severity: VastuSeverity): VastuRule[] => {
  return VASTU_RULES.filter((rule) => rule.severity === severity);
};

export const getRulesForRoom = (roomId: string): VastuRule[] => {
  return VASTU_RULES.filter((rule) => rule.roomTypes.includes(roomId));
};

export const getCriticalRules = (): VastuRule[] => {
  return getRulesBySeverity('critical');
};

export const getDirectionInfo = (direction: VastuDirection): VastuDirectionInfo | undefined => {
  return VASTU_DIRECTIONS.find((d) => d.direction === direction);
};

export const calculateMaxVastuScore = (): number => {
  return VASTU_RULES.reduce((sum, rule) => sum + rule.points, 0);
};

export const searchRules = (query: string): VastuRule[] => {
  const lowerQuery = query.toLowerCase();
  return VASTU_RULES.filter(
    (rule) =>
      rule.title.toLowerCase().includes(lowerQuery) ||
      rule.titleHi.includes(query) ||
      rule.keywords.some((kw) => kw.toLowerCase().includes(lowerQuery))
  );
};

export default VASTU_RULES;